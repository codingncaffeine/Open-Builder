#!/usr/bin/env bash
# Regenerates the declarations of the recovered classes (src/classes, src/*/GeneratedClasses_*.cpp) and builds them:
# the class map from the original (tools/obcmp/obclass), the slots of the hand-declared classes from a build
# (tools/known-slots.sh), what each function pops and does (tools/obcmp/obshape), the declarations and one-line methods
# (tools/obcmp/obdecl). A generated class whose size check fails to compile,
# or whose annotations do not resolve, is excluded and the declarations written again, until the build is clean;
# tools/match.sh then scores what is left.
#   tools/gen-classes.sh
# Reads re/map/functions.tsv, re/map/vtables.tsv and the test bed's program (local, never committed); keeps the class
# map and the exclusions in scratch/classes/.
set -euo pipefail
root="$(cd "$(dirname "$0")/.." && pwd)"
cd "$root"
exe="scratch/testbed/game/Apps/SimCity 4.exe"
bin=scratch/build/obcmp
work=scratch/classes
mkdir -p "$work"
[[ -x "$bin/obclass" && -x "$bin/obdecl" && -x "$bin/obshape" ]] || { echo "build tools/obcmp first (cmake)" >&2; exit 2; }

# The program's allocator and pure-virtual stub (see hook/stubs.txt).
"$bin/obclass" "$exe" re/map/functions.tsv re/map/vtables.tsv --new 0x5e55e0 --delete 0x5e5620 \
  --classes "$work/classes.tsv" --slots "$work/slots.tsv" --deleting "$work/deleting.tsv"
[[ -d build/vc71-good-obj ]] || tools/build.sh >/dev/null 2>&1 || true
tools/known-slots.sh "$work/known.tsv"
# What each function pops and, for the one-line ones, does: signatures, fields and bodies.
"$bin/obshape" "$exe" re/map/functions.tsv --out "$work/shapes.tsv" --sizes "$work/sizes.tsv" \
  --extents "$work/extents.tsv" 2>/dev/null
# Names (src/classes/names.tsv): first rename what was written by hand under the names it was written with (the
# names applied last time, kept in $work/names-applied.tsv; none = the generated cUnk/SlotNN names).
# A generated slot name (SlotNN_<tag>) moves when the slot identities merge differently (a base newly declared): the
# names of the last run ($work/slot-names.tsv, obdecl --slot-names) make those moves renames too.
slotbefore=()
if [[ -s "$work/slot-names.tsv" ]]; then
  cp "$work/slot-names.tsv" "$work/slot-names-before.tsv"
  slotbefore=(--slot-names-before "$work/slot-names-before.tsv")
fi
names=()
if [[ -s src/classes/names.tsv ]]; then
  names=(--names src/classes/names.tsv)
  before=()
  [[ -s "$work/names-applied.tsv" ]] && before=(--names-before "$work/names-applied.tsv")
  "$bin/obdecl" "$work/classes.tsv" "$work/slots.tsv" "$work/deleting.tsv" "$work/known.tsv" --purecall 0x5d4a10 \
    --report "$work/report.tsv" --shapes "$work/shapes.tsv" --extents "$work/extents.tsv" "${names[@]}" "${before[@]}" \
    "${slotbefore[@]}" --slot-names "$work/slot-names.tsv" --rename-map "$work/rename.tsv" | head -1
  tools/names/apply-rename.sh "$work/rename.tsv"
  cp src/classes/names.tsv "$work/names-applied.tsv"
fi
: >"$work/exclude.txt"
for round in 1 2 3 4 5 6; do
  # only what obdecl wrote: headers it marked GENERATED (an edited header and src/classes/ext/ are kept)
  { grep -l -m1 "^// GENERATED by tools/obcmp/obdecl" src/classes/*.h 2>/dev/null || true; } | xargs -r rm -f --
  "$bin/obdecl" "$work/classes.tsv" "$work/slots.tsv" "$work/deleting.tsv" "$work/known.tsv" --purecall 0x5d4a10 \
    --report "$work/report.tsv" --exclude "$work/exclude.txt" --shapes "$work/shapes.tsv" --extents "$work/extents.tsv" \
    "${names[@]}" --slot-names "$work/slot-names.tsv" | head -1
  if tools/build.sh >"$work/build.log" 2>&1; then
    echo "round $round: clean"
    exit 0
  fi
  # src\classes\cUnk00a810e0.h(41) : error C2118: negative subscript  /  gen-hooks: src/classes/cUnk00a810e0.h: ...
  # A class goes into the list by its primary vtable: a cUnk name's own tag, a real name's from src/classes/names.tsv.
  found=$(grep -E 'error C2118|gen-hooks: src/classes/' "$work/build.log" | grep -oE 'classes[\\/][A-Za-z0-9_]+\.h' |
    sed -E 's/^classes.//; s/\.h$//' | sort -u |
    awk -F'\t' 'FNR == NR { if ($1 == "class") tag[$3] = $2; next }
                /^cUnk[0-9a-f]{8}$/ { print substr($0, 5); next }
                $0 in tag { print tag[$0] }' src/classes/names.tsv - || true)
  if [[ -z "$found" ]]; then
    echo "round $round: the build fails for another reason, see $work/build.log" >&2
    exit 1
  fi
  echo "round $round: excluding $(wc -w <<<"$found") classes"
  printf '%s\n' $found >>"$work/exclude.txt"
done
echo "still failing after 6 rounds, see $work/build.log" >&2
exit 1
