    awk -v want="${a#0x}" '
      /=== / { s = $0; sub(/.*=== /, "", s); split(s, w, /[ :]/); cur = w[1]; sub(/^0x/, "", cur); keep = (sprintf("%08x", strtonum("0x" cur)) == want); next }
      keep && /Decompile.java>|INFO|^ *$/ && !/Decompile.java> / { next }
      keep { s = $0; sub(/^.*Decompile\.java> /, "", s); print s }' "$work/ghidra.log" >"$dir/${a#0x}.c"
  done <"$dir/functions.tsv"
  # the Mac reference build's version of each: the packet's own pairs first (translation units), then tools/names
  while IFS=$'\t' read -r a _; do
    w="${a#0x}"
    pair=""
    [[ -s "$dir/pairs.tsv" ]] && pair="$(awk -F'\t' -v w="$w" '$1 == w { print $2 "\t" $3 "\t" $4; exit }' "$dir/pairs.tsv")"
    [[ -n "$pair" ]] || pair="$(awk -F'\t' -v w="$(printf %x "$a")" '$1 == w && $3 != "s" && $4 != "00000000" { print $4 "\t" $2 "\t" $3; exit }' re/names/functions.tsv 2>/dev/null)"
    [[ -n "$pair" ]] || continue
