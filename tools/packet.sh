#!/usr/bin/env bash
# Builds work packets for decompiling: by generated CLASS (every method it declares that is still the original's code,
# plus its helpers), or by original TRANSLATION UNIT (every function still to do in the stretch of the program the
# Mac reference build's symbols tie to one source file). A packet, in scratch/packets/<name>/:
#   functions.tsv   address, size, folder (game or gzcom: the flags it was built with), declaration or name, then
#                   `virtual` (a method a class header declares) or `helper pops N returns R` (a non-virtual function:
#                   N = bytes its ret pops, R = D dword / B bool / F float / V void / ? unknown), and `this` when it
#                   reads ecx first (a member function) or `-` (a free function)
#   <address>.asm   the original's instructions, calls and addresses named where we know them
#   <address>.c     Ghidra's decompilation (a draft: types and names are guesses)
#   <address>.mac.c the same function in the Mac reference build (GCC, with symbols: real names of the function, its
#                   callees and its class), when tools/names found it (re/names/functions.tsv) or, in a translation
#                   unit packet, when its place between two found functions says which it is (found by: p)
#   layout.txt      every field and vtable slot by offset from this (tools/layout.sh; class packets)
# One Ghidra run serves every packet of one invocation.
#   tools/packet.sh cUnk00a87dd0 [cUnk... ...]
#   tools/packet.sh --pick N [MAXSIZE] [MIN-MAX]   N classes with MIN to MAX (default 6-20) such methods of at most
#                                                MAXSIZE bytes each, the most first
#   tools/packet.sh --tu SC4Automata.cpp [...]     by translation unit (a Mac source path or its unique suffix):
#                                                packet tu_SC4Automata
#   tools/packet.sh --pick-tu N [MAXSIZE]          the N translation units with the most functions to do
#   tools/packet.sh --list NAME FILE               the functions still to do whose addresses FILE lists (one per line,
#                                                hex), from any unit: packet NAME (e.g. a family of one shape)
# A class's helpers: the non-virtual functions still to do that (nearly) only its pending methods call, directly or
# through another such helper (the "c" edges of re/names/win/feat.tsv, tools/obcmp/obfeat), two levels deep; a
# function with more than one caller outside the class is a shared utility and stays a STUB.
set -euo pipefail
root="$(cd "$(dirname "$0")/.." && pwd)"
cd "$root"
exe="scratch/testbed/game/Apps/SimCity 4.exe"
out=scratch/packets
mkdir -p "$out"
tools/triage.sh --list >/dev/null  # re/map/triage.tsv
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT
macsrc=scratch/downloads/sc4-research-mac/artifacts/code/Mac-RevA-x86-named/functions
macsyms=scratch/downloads/sc4-research-mac/artifacts/symbols/mac/x86/functions.tsv

# Names: what the stubs and the annotations call each address, demangled ("0x<address>\t<name>").
grep -rhoE '^0x[0-9a-fA-F]+[[:space:]]+\S+' hook/stubs.txt src/classes/stubs.txt | awk '{print tolower($1) "\t" $2}' >"$work/stubs"
paste <(cut -f1 "$work/stubs") <(cut -f2 "$work/stubs" | llvm-undname 2>/dev/null | awk 'BEGIN { RS = ""; FS = "\n" } { print ($2 != "" ? $2 : $1) }') >"$work/names"
for f in $(grep -rlE '// (FUNCTION|SYNTHETIC): 0x' src); do
  awk '/\/\/ (FUNCTION|SYNTHETIC): 0x/ { match($0, /0x[0-9a-fA-F]+/); a = tolower(substr($0, RSTART, RLENGTH)); p = 1; next }
       p { s = $0; sub(/^[ \t\/]*/, "", s); sub(/[ \t]*\{?[ \t]*$/, "", s); printf "0x%08x\t%s\n", strtonum(a), s; p = 0 }' "$f"
done >>"$work/names"
awk '{printf "0x%08x\t%s\n", strtonum("0x" $1), $3 " (library)"}' re/map/libraries.tsv >>"$work/names" 2>/dev/null || true
# what the Mac reference build calls the rest (tools/names/run.sh), position-only guesses left out
awk -F'\t' '$3 != "s" { printf "0x%08x\t%s (mac)\n", strtonum("0x" $1), $2 }' re/names/functions.tsv >>"$work/names" 2>/dev/null || true
# and its service pointers (SL::spCity, ...; tools/names/sl-globals.sh)
awk -F'\t' '{ printf "0x%08x\tSL::%s (mac)\n", strtonum("0x" $1), $2 }' re/names/globals.tsv >>"$work/names" 2>/dev/null || true
awk -F'\t' '{ a = sprintf("0x%08x", strtonum($1)); if (!(a in n)) { n[a] = $2; print a "\t" $2 } }' "$work/names" >"$out/names.tsv"

# sizes: the function list corrected where it ends a function early (scratch/classes/sizes.tsv, by gen-classes.sh)
sizes=re/map/functions.tsv
[[ -f scratch/classes/sizes.tsv ]] && sizes=scratch/classes/sizes.tsv
shapes=scratch/classes/shapes.tsv  # "addr room pops returns shape" (tools/obcmp/obshape)
# generated classes: a header in src/classes marked GENERATED
{ grep -l -m1 "^// GENERATED by tools/obcmp/obdecl" src/classes/*.h 2>/dev/null || true; } | sed 's|.*/||; s|\.h$||' >"$work/generated"
# Candidates: stubbed methods of generated classes whose code is still to do and is real code.
awk -F'\t' 'FILENAME ~ /sizes.tsv$|functions.tsv$/ { real[sprintf("%08x", strtonum("0x" $1))] = strtonum("0x" $2); next }
            FILENAME ~ /generated$/ { gen[$1] = 1; next }
            FILENAME ~ /triage/ { a = sprintf("%08x", strtonum("0x" $1)); if ($3 == "code") code[a] = (a in real) ? real[a] : $2; next }
            { a = tolower($1); sub(/^0x/, "", a); a = sprintf("%08x", strtonum("0x" a))
              if (!(a in code)) next
              cls = $2; sub(/^\?[^@]*@/, "", cls); sub(/@@.*/, "", cls)
              if (!(cls in gen)) { c2 = cls; sub(/_[0-9a-f]+$/, "", c2); if (!(c2 in gen)) next; cls = c2 }
              print cls "\t" a "\t" code[a] "\t" $2 }' "$sizes" re/map/triage.tsv "$work/generated" "$work/stubs" | sort -u >"$work/candidates"
awk '{ n = split($4, s, ","); for (i = 1; i <= n; i++) printf "%08x\n", strtonum("0x" s[i]) }' re/map/vtables.tsv | sort -u >"$work/virtual"
awk -F'\t' '{ a = tolower($1); sub(/^0x/, "", a); printf "%08x\n", strtonum("0x" a) }' "$work/stubs" | sort -u >"$work/stubbed"
awk -F'\t' '$2 == "c" { print $1 "\t" $3 }' re/names/win/feat.tsv >"$work/calls"
done_list="$(ls "$out" 2>/dev/null | grep -v '^names.tsv$' || true)"

# "this" when a function reads ecx before writing it (a member function: this in ecx), "-" otherwise
thisness() {  # address (8 hex), size
  objdump -d -M intel --no-show-raw-insn --start-address="0x$1" --stop-address="$((0x$1 + $2))" "$exe" |
    awk -F'\t' 'done { next } /^ *[0-9a-f]+:\t/ {  # reads to the end: an early exit would SIGPIPE objdump
      i = $2
      if (i ~ /^call/) { r = "-"; done = 1; next }
      if (i !~ /ecx/) next
      if (i ~ /^(mov|lea|movzx|movsx) +ecx,/) { s = i; sub(/^[a-z]+ +ecx,/, "", s); r = (s ~ /ecx/) ? "this" : "-"; done = 1; next }
      if (i ~ /^(pop +ecx|xor +ecx,ecx)/) { r = "-"; done = 1; next }
      r = "this"; done = 1 }
      END { print (r == "" ? "-" : r) }'
}
shapeof() {  # address (8 hex): "pops N returns R"
  awk -v w="$(printf %x "0x$1")" '$1 == w { print "pops " $3 " returns " $4; exit }' "$shapes" 2>/dev/null
}
macname() {  # address (8 hex): the Mac name when tools/names found it
  awk -F'\t' -v w="$(printf %x "0x$1")" '$1 == w && $3 != "s" { print $2 " (mac)"; exit }' re/names/functions.tsv 2>/dev/null
}

packets=()
mode=class
case "${1:-}" in
  --tu) mode=tu; shift; tus=("$@") ;;
  --pick-tu) mode=tu; n="${2:?how many}" max="${3:-1024}" ;;
  --list) mode=tu; listname="${2:?a packet name}"; listfile="$(realpath "${3:?an address file}")"; tus=("$listname") ;;
esac

if [[ $mode == tu ]]; then
  # Every function still to do, attributed to the translation unit of the Mac build whose found functions surround it
  # (the same unit before and after it in address order), paired with the Mac function at the same place between the
  # two when the unit has exactly as many unfound functions there (how = p); else its candidates are listed.
  # "<tu>\t<address>\t<size>\t<kind>\t<name>\t<how>\t<mac>\t<decl>"
  [[ -f re/names/mac/tu.tsv && -f "$macsyms" ]] || { echo "needs re/names/mac/tu.tsv (the Mac symbol table) for --tu" >&2; exit 2; }
  # the class whose vtable holds each virtual function (the headers' VTABLE annotations)
  for h in src/classes/*.h; do
    { grep -oE '^// VTABLE: 0x[0-9a-fA-F]+' "$h" || true; } | awk -v c="$(basename "$h" .h)" '{ printf "%08x\t%s\n", strtonum($3), c }'
  done | awk -F'\t' 'FILENAME ~ /vtables.tsv$/ { v = sprintf("%08x", strtonum("0x" $1)); n = split($4, s, ","); for (i = 1; i <= n; i++) slot[v] = slot[v] " " sprintf("%08x", strtonum("0x" s[i])); next }
                     { n = split(slot[$1], s, " "); for (i = 1; i <= n; i++) if (!(s[i] in seen)) { seen[s[i]] = 1; print s[i] "\t" $2 } }' re/map/vtables.tsv - >"$work/vtclass"
  awk -F'\t' '
    FILENAME ~ /tu.tsv$/ { p = $2; sub(/.*\/RH_Merge\//, "", p); sub(/.*\/SC4RH\//, "", p); tuof[$1] = p; next }
    FILENAME ~ /x86\/functions/ { mname[$1] = $3; next }
    FILENAME ~ /mac\/funcs/ { msz[$1] = $2; next }
    FILENAME ~ /vtclass$/ { vcls[$1] = $2; next }
    FILENAME ~ /re\/names\/functions/ { if ($3 == "s") next; w = sprintf("%08x", strtonum("0x" $1)); wname[w] = $2; whow[w] = $3; wmac[w] = $4; macused[$4] = 1; next }
    FILENAME ~ /triage/ { a = sprintf("%08x", strtonum("0x" $1)); if ($3 == "code") todo[a] = $2 + 0; next }
    FILENAME ~ /virtual$/ { virt[$1] = 1; next }
    FILENAME ~ /stubs$/ { a = tolower($1); sub(/^0x/, "", a); a = sprintf("%08x", strtonum("0x" a)); decl[a] = $2; next }
    { split($0, q, / +/); a = sprintf("%08x", strtonum("0x" q[1])); all[++N] = a; sz[a] = strtonum("0x" q[2]) }
    # WC, WM: the class and method a Windows function is declared as (its stub name "?Method@Class@@...", or the class
    # whose vtable holds it); a generated name (cUnk..., SlotNN) counts as unknown
    function wsplit(b,   d, s, p) {
      WC = ""; WM = ""
      if (b in decl) {
        d = decl[b]
        if (substr(d, 1, 1) == "?" && substr(d, 2, 1) != "?") {
          s = substr(d, 2); p = index(s, "@"); WM = substr(s, 1, p - 1); s = substr(s, p + 1); p = index(s, "@"); WC = substr(s, 1, p - 1)
        }
      } else if (b in vcls) WC = vcls[b]
      if (WC ~ /^cUnk00/) WC = ""
      if (WM ~ /^Slot[0-9]/) WM = ""
    }
    # MC, MM: the innermost class and the method of a Mac name "ns::Class::Method(args)"
    function msplit(n,   p) {
      MC = ""; MM = n; p = index(n, "("); if (p) MM = substr(n, 1, p - 1)
      while ((p = index(MM, "::")) > 0) { MC = substr(MM, 1, p - 1); MM = substr(MM, p + 2) }
    }
    END {
      for (m in tuof) if (!(m in macused)) free[tuof[m]] = free[tuof[m]] " " m  # unfound Mac functions, per unit
      for (t in free) { n = split(free[t], l, " "); asort(l); s = ""; for (i = 1; i <= n; i++) s = s " " l[i]; free[t] = s }
      # anchors: found functions with a unit; walk the program, a stretch between two anchors of one unit is its
      prev = 0
      for (i = 1; i <= N; i++) {
        a = all[i]
        if (!((a in wmac) && (wmac[a] in tuof))) continue
        t = tuof[wmac[a]]
        if (a in todo) print t "\t" a "\t" sz[a] "\t" ((a in virt) ? "virtual" : "helper") "\t" wname[a] "\t" whow[a] "\t" wmac[a] "\t" ((a in decl) ? decl[a] : "-")
        if (prev && tuof[wmac[all[prev]]] == t) {
          # the functions to do between the two anchors, and the unfound Mac functions of the unit between their Mac places
          nw = 0; delete W
          for (x = prev + 1; x < i; x++) if ((all[x] in todo) && !(all[x] in wmac)) W[++nw] = all[x]
          nm = 0; delete Mc
          m1 = wmac[all[prev]]; m2 = wmac[a]
          if (m1 < m2) { n = split(free[t], l, " "); for (y = 1; y <= n; y++) if (l[y] > m1 && l[y] < m2 && !(l[y] in macused)) Mc[++nm] = l[y] }
          # pair them in order: a method name both sides spell the same (class and method) weighs 2, a similar size
          # (within a third; tiny ones freely) weighs 1 and, for a virtual function, only inside its own class
          delete f; delete pm; delete pw
          for (x = 0; x <= nw; x++) f[x, 0] = 0
          for (y = 0; y <= nm; y++) f[0, y] = 0
          for (x = 1; x <= nw; x++) {
            wsplit(W[x]); wc = WC; wm = WM
            for (y = 1; y <= nm; y++) {
              s1 = sz[W[x]]; s2 = msz[Mc[y]] + 0
              msplit(mname[Mc[y]])
              # (pairing by place and size alone was tried: 0 of 20 right on the pilot unit — only a name match pairs)
              w = 0
              if (wc != "" && wm != "" && wc == MC && wm == MM) w = 2
              best = f[x - 1, y]; if (f[x, y - 1] > best) best = f[x, y - 1]
              if (w && f[x - 1, y - 1] + w > best) best = f[x - 1, y - 1] + w
              f[x, y] = best; pw[x, y] = w
            }
          }
          x = nw; y = nm
          while (x > 0 && y > 0) {
            if (f[x, y] == f[x - 1, y]) x--
            else if (f[x, y] == f[x, y - 1]) y--
            else { pm[x] = y; x--; y-- }
          }
          for (x = 1; x <= nw; x++) {
            b = W[x]; kind = (b in virt) ? "virtual" : "helper"
            d = (b in decl) ? decl[b] : (b in vcls) ? "slot of " vcls[b] : "-"
            if (x in pm) { macused[Mc[pm[x]]] = 1; print t "\t" b "\t" sz[b] "\t" kind "\t" mname[Mc[pm[x]]] "\t" (pw[x, pm[x]] == 2 ? "n" : "p") "\t" Mc[pm[x]] "\t" d }
            else {
              c = ""; k = 0
              for (y = 1; y <= nm && k < 3; y++) { used = 0; for (z in pm) if (pm[z] == y) used = 1; if (!used) { c = c (c == "" ? "" : " | ") mname[Mc[y]]; k++ } }
              print t "\t" b "\t" sz[b] "\t" kind "\t" (c != "" ? "? " c : "-") "\t-\t-\t" d
            }
          }
        }
        prev = i
      }
    }' re/names/mac/tu.tsv "$macsyms" re/names/mac/funcs.tsv "$work/vtclass" re/names/functions.tsv re/map/triage.tsv "$work/virtual" "$work/stubs" re/map/functions.tsv |
    sort -t$'\t' -k1,1 -k2,2 >"$work/tu-all"
  if [[ "${1:-}" == "--pick-tu" ]]; then
    mapfile -t tus < <(awk -F'\t' -v max="$max" '$3 <= max { c[$1]++ } END { for (t in c) print c[t] "\t" t }' "$work/tu-all" | sort -k1,1nr -k2 |
      cut -f2 | while read -r t; do b="$(basename "$t")"; grep -qxF "tu_${b%.*}" <<<"$done_list" || echo "$t"; done | head -n "$n")
  fi
  ((${#tus[@]})) || { echo "no translation units" >&2; exit 2; }
  for t in "${tus[@]}"; do
    if [[ -n "${listfile:-}" ]]; then
      name="$listname"
    else
      # the unit: an exact path, or the unique path ending in the argument
      full="$(cut -f1 "$work/tu-all" | sort -u | awk -v t="$t" '$0 == t || substr($0, length($0) - length(t) + 1) == t || substr($0, length($0) - length(t)) == "/" t')"
      [[ -n "$full" && "$(wc -l <<<"$full")" -eq 1 ]] || { echo "no unique translation unit for '$t'" >&2; continue; }
      name="tu_$(basename "${full%.*}")"
    fi
    dir="$out/$name"
    mkdir -p "$dir"
    rm -f "$dir"/*.asm "$dir"/*.c
    if [[ -n "${listfile:-}" ]]; then
      # a listed function no unit claims (no Mac function around it) still gets its row: kind, size and declaration
      awk -F'\t' 'FILENAME == ARGV[1] { want[sprintf("%08x", strtonum("0x" $1))] = 1; next }
                  FILENAME == ARGV[2] { if ($2 in want) { print; have[$2] = 1 } next }
                  FILENAME == ARGV[3] { virt[$1] = 1; next }
                  FILENAME == ARGV[4] { a = $1; sub(/^0x/, "", a); decl[sprintf("%08x", strtonum("0x" a))] = $2; next }
                  { split($0, q, / +/); a = sprintf("%08x", strtonum("0x" q[1]))
                    if ((a in want) && !(a in have)) print "-\t" a "\t" strtonum("0x" q[2]) "\t" ((a in virt) ? "virtual" : "helper") "\t-\t-\t-\t" ((a in decl) ? decl[a] : "-") }' \
        "$listfile" "$work/tu-all" "$work/virtual" "$work/stubs" re/map/functions.tsv >"$work/$name.rows"
    else
      awk -F'\t' -v t="$full" '$1 == t' "$work/tu-all" >"$work/$name.rows"
    fi
    folder=$(awk -F'\t' '{ n++; if (strtonum("0x" $2) % 16) u++ } END { print (u * 2 > n ? "gzcom" : "game") }' "$work/$name.rows")
    : >"$dir/pairs.tsv"  # "<address>\t<mac address>\t<name>\t<how>"
    while IFS=$'\t' read -r _ a size kind nm how mac decl; do
      if [[ $kind == virtual ]]; then
        d="$decl"
        [[ $decl == \?* ]] && d="$(llvm-undname "$decl" 2>/dev/null | sed -n 2p)"
        [[ $decl == - ]] && d="virtual (no class header declares it)"
        [[ "$nm" == - ]] && nm=""
        [[ "$how" == p ]] && how="by position"
        printf '0x%s\t%s\t%s\t%s\tvirtual\t-\n' "$a" "$size" "$folder" "${d:-$decl}${nm:+ = $nm (mac, $how)}"
      else
        label="$nm"
        [[ "$nm" == - ]] && label="Fn$a"
        [[ "$how" == p || "$how" == - ]] || label="$nm (mac, $how)"
        [[ "$how" == p ]] && label="$nm (mac, by position)"
        printf '0x%s\t%s\t%s\t%s\t%s %s\t%s\n' "$a" "$size" "$folder" "$label" "$kind" "$(shapeof "$a")" "$(thisness "$a" "$size")"
      fi
      [[ "$mac" != - ]] && printf '%s\t%s\t%s\t%s\n' "$a" "$mac" "$nm" "$how" >>"$dir/pairs.tsv"
    done <"$work/$name.rows" >"$dir/functions.tsv"
    cut -f2 "$work/$name.rows" >>"$work/all-addresses"
    echo "# ${full:-$name}: $(cut -f8 "$work/$name.rows" | sed -E 's/^\?[^@]*@//; s/@@.*//' | grep -v '^-$' | sort | uniq -c | sort -rn | head -8 | awk '{printf "%s x%d, ", $2, $1}')" >"$dir/layout.txt"
    packets+=("$name")
  done
else
  classes=()
  if [[ "${1:-}" == "--pick" ]]; then
    n="${2:?how many}" max="${3:-400}" range="${4:-6-20}"
    mapfile -t classes < <(awk -F'\t' -v max="$max" -v lo="${range%-*}" -v hi="${range#*-}" '$3 <= max { c[$1]++ } END { for (k in c) if (c[k] >= lo && c[k] <= hi) print c[k] "\t" k }' "$work/candidates" |
      sort -k1,1nr -k2 | cut -f2 | grep -vxF -f <(printf '%s\n' $done_list "") | head -n "$n")
  else
    classes=("$@")
  fi
  ((${#classes[@]})) || { echo "no classes" >&2; exit 2; }
  max="${max:-1024}"
  for cls in "${classes[@]}"; do
    dir="$out/$cls"
    mkdir -p "$dir"
    rm -f "$dir"/*.asm "$dir"/*.c  # listings of an earlier packet (its report.md stays)
    # one line per function (a function several decorated names share is one function)
    awk -F'\t' -v c="$cls" '$1 == c && !seen[$2]++' "$work/candidates" >"$work/$cls"
    # The folder (its flags) from where the original put the functions: the game was built with function-level linking
    # (every function 16-aligned), the framework packed; most of a class's methods off a 16-byte boundary = framework.
    folder=$(awk -F'\t' '{ n++; if (strtonum("0x" $2) % 16) u++ } END { print (u * 2 > n ? "gzcom" : "game") }' "$work/$cls")
    paste <(cut -f2 "$work/$cls") <(cut -f3 "$work/$cls") <(cut -f4 "$work/$cls" | llvm-undname 2>/dev/null | awk 'BEGIN { RS = ""; FS = "\n" } { print ($2 != "" ? $2 : $1) }') |
      awk -F'\t' -v f="$folder" '{ print "0x" $1 "\t" $2 "\t" f "\t" $3 "\tvirtual\t-" }' >"$dir/functions.tsv"
    cut -f2 "$work/$cls" >>"$work/all-addresses"
    # the class's helpers (see above): "<address> <size>"
    awk -F'\t' -v max="$max" '
      FILENAME ~ /calls$/ { callee[$1] = callee[$1] " " $2; callers[$2] = callers[$2] " " $1; next }
      FILENAME ~ /virtual$/ { virt[$1] = 1; next }
      FILENAME ~ /stubbed$/ { owned[$1] = 1; next }
      # sizes.tsv: the function list corrected where it ends a function early (triage.tsv has the uncorrected sizes)
      FILENAME ~ /sizes.tsv$/ { real[sprintf("%08x", strtonum("0x" $1))] = strtonum("0x" $2); next }
      FILENAME ~ /triage/ { a = sprintf("%08x", strtonum("0x" $1)); if ($3 == "code") todo[a] = (a in real) ? real[a] : $2; next }
      { set[$2] = 1; level[$2] = 0 }
      END {
        for (round = 1; round <= 2; round++)
          for (f in set) {
            if (level[f] != round - 1) continue
            n = split(callee[f], cs, " ")
            for (i = 1; i <= n; i++) {
              c = cs[i]
              if ((c in set) || !(c in todo) || (c in virt) || (c in owned) || todo[c] + 0 > max + 0) continue
              m = split(callers[c], ks, " "); out = 0; delete d
              for (j = 1; j <= m; j++) if (!(ks[j] in set) && !(ks[j] in d)) { d[ks[j]] = 1; out++ }
              if (out > 1) continue
              set[c] = 1; level[c] = round; print c "\t" todo[c]
            }
          }
      }' "$work/calls" "$work/virtual" "$work/stubbed" $([[ $sizes == *sizes.tsv ]] && echo "$sizes") re/map/triage.tsv "$work/$cls" | sort -u >"$work/$cls.helpers"
    while IFS=$'\t' read -r a size; do
      name="$(macname "$a")"
      printf '0x%s\t%s\t%s\t%s\thelper %s\t%s\n' "$a" "$size" "$folder" "${name:-Fn$a}" "$(shapeof "$a")" "$(thisness "$a" "$size")"
    done <"$work/$cls.helpers" >>"$dir/functions.tsv"
    cut -f1 "$work/$cls.helpers" >>"$work/all-addresses"
    tools/layout.sh "$cls" >"$dir/layout.txt" 2>/dev/null || echo "# clang could not lay out $cls" >"$dir/layout.txt"
    # A "method" that never reads ecx is no method: a vtable whose extent ran into a table of plain functions (one
    # 6-slot vtable came with 168 blit kernels behind it). Counted and said, so such a class is not handed out.
    nomethod=0
    while IFS=$'\t' read -r a size _ _ kind _; do
      [[ $kind == virtual && "$(thisness "${a#0x}" "$size")" == - ]] && nomethod=$((nomethod + 1))
    done <"$dir/functions.tsv"
    (( nomethod )) && echo "$cls: $nomethod of its virtual rows never read ecx (not methods: a function table in the vtable's extent?)"
    packets+=("$cls")
  done
fi

# The listings of every packet: the original's instructions with names, Ghidra's drafts (one run for all), the Mac
# reference build's version where known.
for name in "${packets[@]}"; do
  dir="$out/$name"
  while IFS=$'\t' read -r a size _; do
    objdump -d -M intel --no-show-raw-insn --start-address="$a" --stop-address="$((a + size))" "$exe" |
      awk -F'\t' 'FILENAME ~ /names.tsv$/ { n[$1] = $2; next }
        /^ *[0-9a-f]+:\t/ {
          line = $2
          if (match(line, /0x[0-9a-f]+/) || match(line, /^(call|jmp) +[0-9a-f]+/)) {
            s = line; out = ""
            while (match(s, /(0x)?[0-9a-f]{6,8}/)) {
              h = substr(s, RSTART, RLENGTH); v = sprintf("0x%08x", strtonum(h ~ /^0x/ ? h : "0x" h))
              out = out substr(s, 1, RSTART + RLENGTH - 1) ((v in n) ? " <" n[v] ">" : "")
              s = substr(s, RSTART + RLENGTH)
            }
            line = out s
          }
          sub(/^ +/, "", $1); print $1 "\t" line
        }' "$out/names.tsv" - >"$dir/${a#0x}.asm"
  done <"$dir/functions.tsv"
done
