  done <"$dir/functions.tsv"
  echo "$dir: $(wc -l <"$dir/functions.tsv") functions ($(grep -c $'\thelper' "$dir/functions.tsv" || true) helpers, $(ls "$dir"/*.mac.c 2>/dev/null | wc -l) with .mac.c)"
