#!/usr/bin/env python3
# Writes a translation unit of explicit STLport instantiations over many element types, for tools/stl/run.sh: the
# 2003 compiler builds it, and tools/obcmp/obsig --twins finds each instance in the original. The original's element
# types are unknown, but code depends only on a type's shape: its size, how it compares (signed, unsigned, float) and
# whether copying it runs code. So one stand-in per shape: pointers stand for every pointer, PODs of N bytes (S<N>)
# for every plain struct of that size; obsig takes identical instances as one.
#   tools/stl/catalogue.py > catalogue.cpp
import itertools

sizes = [8, 12, 16, 20, 24, 28, 32, 36, 40, 44, 48, 52, 56, 60, 64, 72, 80, 96, 128]
pods = [f"S{n}" for n in sizes]

# keys: everything that orders differently or compares through code
keys = ["int", "unsigned int", "short", "unsigned short", "signed char", "unsigned char", "float", "double",
        "__int64", "unsigned __int64", "_STL::pair<int, int>", "_STL::pair<unsigned int, unsigned int>",
        "_STL::string"]
# values: everything that copies differently (int-sized values copy like a pointer)
values = ["void*", "char", "short", "double", "_STL::string", "_STL::vector<void*>", "_STL::list<void*>",
          "_STL::pair<int, int>"] + pods
hash_keys = ["int", "unsigned int", "unsigned short", "_STL::string"]
sequence = sorted(set(values + keys + ["int", "float", "bool", "unsigned char"]))

out = ["// Generated by tools/stl/catalogue.py: explicit STLport instantiations, one per element shape.",
       "#include <string>", "#include <vector>", "#include <list>", "#include <map>", "#include <set>",
       "#include <deque>", "#include <hash_map>", "#include <hash_set>", "#include <algorithm>",
       "#include \"gzcom/cGZAllocatorServiceSTLAllocator.h\"", "",
       "// one cache for every catalogue instance (obsig reads the original's caches, one per element type, as alike)",
       "struct CatalogueKey;",
       "template <class Key> cIGZAllocatorService* cGZAllocatorServiceCache<Key>::spService = 0;", ""]
for n in sizes:
    # a plain struct of n bytes; == and < so every member of every container compiles
    out.append(f"struct S{n} {{ int w[{n // 4}]; }};")
    out.append(f"inline bool operator==(const S{n}& a, const S{n}& b) {{ return a.w[0] == b.w[0]; }}")
    out.append(f"inline bool operator<(const S{n}& a, const S{n}& b) {{ return a.w[0] < b.w[0]; }}")
out.append("")
seen = set()
def inst(t):
    if t not in seen:
        seen.add(t)
        out.append(f"template class {t};")
for t in sequence:
    for c in ["vector", "list", "deque"]:
        inst(f"_STL::{c}<{t} >")
for k in keys:
    inst(f"_STL::set<{k} >")
    inst(f"_STL::multiset<{k} >")
for k, v in itertools.product(keys, values):
    inst(f"_STL::map<{k}, {v} >")
for k, v in itertools.product(["int", "unsigned int"], values):
    inst(f"_STL::multimap<{k}, {v} >")
for k in hash_keys:
    inst(f"_STL::hash_set<{k} >")
    for v in values:
        inst(f"_STL::hash_map<{k}, {v} >")
# The game's own containers allocate from the framework's allocator service (cGZAllocatorServiceSTLAllocator)
gz = lambda t: f"cGZAllocatorServiceSTLAllocator<{t}, CatalogueKey >"
gz_values = ["void*", "char", "short", "double", "_STL::pair<int, int>"] + pods
for t in gz_values + ["int", "unsigned char", "unsigned short", "float"]:
    for c in ["vector", "list", "deque"]:
        inst(f"_STL::{c}<{t}, {gz(t)} >")
inst(f"_STL::basic_string<char, _STL::char_traits<char>, {gz('char')} >")
for k in keys:
    inst(f"_STL::set<{k}, _STL::less<{k} >, {gz(k)} >")
for k, v in itertools.product(keys, gz_values):
    inst(f"_STL::map<{k}, {v}, _STL::less<{k} >, {gz(f'_STL::pair<const {k}, {v} >')} >")
print("\n".join(out))
