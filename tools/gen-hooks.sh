#!/usr/bin/env bash
# Writes the hook table (hook/hooks.h) from the "// FUNCTION: 0x<address>" annotations in src/: each annotation
# names the original address of the function defined on the next line that holds a "Name(" or "Class::Name(".
#   tools/gen-hooks.sh <out.cpp>
# "// FUNCTION: 0x<address> nohook" matches the function without hooking it (one too small for a 5-byte jump).
set -euo pipefail
root="$(cd "$(dirname "$0")/.." && pwd)"
out="$1"
cd "$root"
mapfile -t sources < <(find src -name '*.cpp' | sort)
{
  echo '// Generated by tools/gen-hooks.sh from the FUNCTION annotations in src/. Do not edit.'
  echo '#include "hooks.h"'
  echo
  for h in $(find src -name '*.h' | sort); do echo "#include \"${h#src/}\""; done
  echo
  echo '#pragma data_seg(".obhook")'
  echo '#pragma const_seg(".obhook")'
  echo
  echo 'const HookEntry g_hooks[] = {'
  if ((${#sources[@]})); then
    awk '
      /\/\/ FUNCTION: 0x[0-9a-fA-F]+/ {
        match($0, /0x[0-9a-fA-F]+/); address = substr($0, RSTART, RLENGTH); hook = ($0 !~ /nohook/); pending = 1; next
      }
      pending && match($0, /[A-Za-z_~][A-Za-z0-9_:~]*[ \t]*\(/) {
        name = substr($0, RSTART, RLENGTH); sub(/[ \t]*\($/, "", name)
        printf "    { %s, FunctionAddress(&%s), \"%s\", %d },\n", address, name, name, hook
        pending = 0
      }' "${sources[@]}"
  fi
  echo '    { 0, 0, 0, 0 },  // keeps the array non-empty; never installed'
  echo '};'
  echo
  echo '#pragma const_seg()'
  echo '#pragma data_seg()'
  echo
  echo 'const unsigned g_hookCount = sizeof g_hooks / sizeof g_hooks[0] - 1;'
} >"$out"
